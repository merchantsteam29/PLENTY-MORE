#!/usr/bin/env node
// Builds the recording script for voice actors from js/story.js.
//   node tools/voice-script.js
// Writes VOICE_SCRIPT.md (per character, in story order) and voice/lines.csv.
// Each line's ID is the same hash the game computes at runtime (G.lineId in js/main.js),
// so an actor's file saved as voice/<ID>.mp3 plays automatically for that line.
const fs = require('fs'), path = require('path');
const root = path.join(__dirname, '..');
const src = fs.readFileSync(path.join(root, 'js', 'story.js'), 'utf8');

const lineId = (who, text) => { let h = 2166136261; const s = who + '|' + text; for (let i = 0; i < s.length; i++) { h ^= s.charCodeAt(i); h = Math.imul(h, 16777619); } return who + '_' + (h >>> 0).toString(36); };
const STR = String.raw`'((?:[^'\\]|\\.)*)'|"((?:[^"\\]|\\.)*)"`;
const unq = (a, b) => (a !== undefined ? a.replace(/\\'/g, "'").replace(/\\\\/g, '\\') : JSON.parse('"' + b + '"'));
const CH = ['leon', 'luke', 'lily', 'rose', 'linda'];
const NAMES = { leon: 'Leon (13)', luke: 'Luke (20)', lily: 'Lily (17)', rose: 'Rose (15)', linda: 'Mom / Linda (44)' };
const NOTES = {
  leon: 'Youngest. Quiet, observant, hungry. Thoughts are internal monologue: close-mic, low, intimate.',
  luke: 'Big brother. Very online; narrates life to an imaginary "chat"; idolizes streamer Kaylie. Jokey, warm underneath.',
  lily: 'Calm, gentle, joyful in small things. Draws everything. The steady one, until she is scared.',
  rose: 'Loves flowers and knows all their names. Stubborn, brave, a little prickly, very sweet with Leon.',
  linda: 'Loving, exhausted single mother who slowly becomes something else. Never play her as a cartoon villain: she believes she is saving them.'
};
const scenes = [...src.matchAll(/async function (day\d|basement|ending)\(|function (\w+Flavor)\(/g)].map(m => ({ i: m.index, name: m[1] || m[2] }));
const sceneAt = i => { let s = 'misc'; for (const x of scenes) if (x.i <= i) s = x.name; return s; };
const dirOf = (opts, thought) => {
  const d = []; if (thought) d.push('thought (internal)');
  if (!opts) return d.join(', ');
  const g = k => (opts.match(new RegExp(k + String.raw`\s*:\s*'([^']*)'`)) || [])[1];
  if (/yell\s*:\s*true/.test(opts)) d.push('YELLING'); if (/whisper\s*:\s*true/.test(opts)) d.push('whisper');
  const mood = g('mood'); if (mood) d.push(mood); const dir = g('dir'); if (dir) d.push(dir);
  if (/auto\s*:\s*0/.test(opts)) d.push('cut off mid-word');
  return d.join(', ');
};
const found = [];
const add = (who, text, opts, idx, thought) => { if (!CH.includes(who)) return; found.push({ who, text, dir: dirOf(opts, thought), scene: sceneAt(idx), id: lineId(who, text), idx }); };
for (const m of src.matchAll(new RegExp(String.raw`\bsay\(\s*'(\w+)'\s*,\s*(?:${STR})\s*(?:,\s*(\{[^}]*\}))?`, 'g'))) add(m[1], unq(m[2], m[3]), m[4], m.index, false);
for (const m of src.matchAll(new RegExp(String.raw`\bthink\(\s*(?:${STR})\s*(?:,\s*(\{[^}]*\}))?`, 'g'))) add('leon', unq(m[1], m[2]), m[3], m.index, true);
for (const m of src.matchAll(new RegExp(String.raw`\[\s*'(\w+)'\s*,\s*(?:${STR})\s*(?:,\s*(\{[^}]*\}))?\s*\]`, 'g'))) { const t = unq(m[2], m[3]); if (/[\s.!?,]/.test(t)) add(m[1], t, m[4], m.index, false); }
found.sort((a, b) => a.idx - b.idx);
const seen = new Set(), lines = found.filter(l => (seen.has(l.id) ? false : seen.add(l.id)));

const esc = s => s.replace(/\|/g, '\\|');
let md = `# PLENTY MORE — Voice Recording Script\n\nGenerated by \`node tools/voice-script.js\` from \`js/story.js\`. **${lines.length} lines.**\n\n`;
md += `## How it works\n\n1. Record each line and save it as \`voice/<ID>.mp3\` (\`.ogg\`, \`.wav\` and \`.m4a\` also work). Example: \`voice/${lines[0] ? lines[0].id : 'luke_abc123'}.mp3\`.\n2. Run \`node tools/voice-manifest.js\` to register the files.\n3. Done. Recorded lines play in the game with lip sync and 3D positioning, and the text scrolls at the speed of the recording. Lines without a file keep the synthesized murmur.\n\n`;
md += `Notes for actors:\n- Mono, 44.1 or 48 kHz, no music or effects. Leave about 0.2 s of silence at each end.\n- Directions in the table come from the script (mood, yell, whisper). "thought" lines are Leon's inner voice, so keep them close and quiet.\n- If a line changes in \`story.js\` its ID changes too. Re-run this script and re-record that line.\n\n`;
for (const who of CH) {
  const L = lines.filter(l => l.who === who); if (!L.length) continue;
  md += `## ${NAMES[who]} — ${L.length} lines\n\n_${NOTES[who]}_\n\n| ID | Line | Direction | Scene |\n|---|---|---|---|\n`;
  for (const l of L) md += `| \`${l.id}\` | ${esc(l.text)} | ${esc(l.dir)} | ${l.scene} |\n`;
  md += '\n';
}
fs.writeFileSync(path.join(root, 'VOICE_SCRIPT.md'), md);
const csvq = s => '"' + String(s).replace(/"/g, '""') + '"';
fs.writeFileSync(path.join(root, 'voice', 'lines.csv'), 'id,character,line,direction,scene\n' + lines.map(l => [l.id, l.who, l.text, l.dir, l.scene].map(csvq).join(',')).join('\n') + '\n');
const per = CH.map(w => `${w}: ${lines.filter(l => l.who === w).length}`).join(', ');
console.log(`Wrote VOICE_SCRIPT.md and voice/lines.csv: ${lines.length} lines (${per})`);
