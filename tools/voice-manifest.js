#!/usr/bin/env node
// Scans voice/ for recorded lines and writes voice/manifest.js so the game can find them.
//   node tools/voice-manifest.js
// Files must be named <ID>.<ext>, where <ID> comes from VOICE_SCRIPT.md (e.g. luke_1x2y3z.mp3).
const fs = require('fs'), path = require('path');
const dir = path.join(__dirname, '..', 'voice');
const exts = new Set(['.mp3', '.ogg', '.wav', '.m4a', '.webm']);
const known = new Set();
try { for (const row of fs.readFileSync(path.join(dir, 'lines.csv'), 'utf8').split('\n').slice(1)) { const id = (row.match(/^"([^"]+)"/) || [])[1]; if (id) known.add(id); } } catch (e) { /* no csv yet */ }
const map = {}, unknown = [];
for (const f of fs.readdirSync(dir).sort()) {
  const ext = path.extname(f).toLowerCase(); if (!exts.has(ext)) continue;
  const id = path.basename(f, path.extname(f)); map[id] = f;
  if (known.size && !known.has(id)) unknown.push(f);
}
const body = `// Recorded voice lines. Generated by \`node tools/voice-manifest.js\` from the audio files in this folder.\n// Maps a line id (see VOICE_SCRIPT.md) to its file. Lines without a file use the synthesized murmur.\nwindow.G = window.G || {};\nG.VOICE_FILES = ${JSON.stringify(map, null, 2)};\n`;
fs.writeFileSync(path.join(dir, 'manifest.js'), body);
console.log(`voice/manifest.js: ${Object.keys(map).length} recorded line(s).`);
if (known.size) console.log(`Coverage: ${Object.keys(map).filter(k => known.has(k)).length}/${known.size} script lines recorded.`);
if (unknown.length) console.log('Warning: these files do not match any line in the current script (renamed or outdated?):\n  ' + unknown.join('\n  '));
